#!/usr/bin/env bash
#
# The load test (ADR-0198): a replicated Rahdar of its own, brokers, seeded data, the Gatling simulation, a report.
#
#   scripts/load.sh [PROFILE]        PROFILE is load/profiles/<PROFILE>.env: reference (default) or smoke
#
# The stack is compose project rahdar-load on 127.0.0.1:$LOAD_PORT (default 18090), apart from the
# development stack and the demo. It starts from the image LOAD_IMAGE, or from the jar LOAD_JAR run in the released
# runtime image, or from an image built here from the Dockerfile. It is removed with its volumes on every exit.
# Every size in the profile can be overridden (the brokers are clusters x nodes per cluster, one container each) from the environment, for example `LOAD_QUEUES=5000 just load`.
#
# Writes load/target/report/summary.{json,md}; exits 1 on a Gatling assertion or a figure below its published target.
# Runs on bash 3.2 and Linux: no mapfile, no ${x,,}, no GNU-only flags.
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$root"
profile=${1:-reference}
[ -f "load/profiles/$profile.env" ] || { echo "no profile load/profiles/$profile.env" >&2; exit 2; }
# shellcheck source=/dev/null
. "load/profiles/$profile.env"

# A broker belongs to one cluster (Rahdar refuses to register it twice), so the clusters need distinct brokers.
LOAD_BROKERS=$((LOAD_CLUSTERS * LOAD_NODES_PER_CLUSTER))
LOAD_PORT=${LOAD_PORT:-18090}
# LOAD_TCP_WMEM="4096 4096 4096" shrinks the Rahdar containers' TCP send buffers, so that a subscriber that stops
# reading blocks the server's write after a few kilobytes instead of a few megabytes (the stall profile uses it).
# A broker holding thousands of queues needs more than 256 MB of heap (it runs out of memory at about 3,000).
LOAD_BROKER_HEAP=${LOAD_BROKER_HEAP:-256}
# Rahdar walks a node's whole queue list every tier-C tick (5 minutes by default). The load stack ticks every 15 s so
# that queues seeded after start-up are known within the run; its broker reads are more frequent than a default
# installation's, never less.
LOAD_TIER_C=${LOAD_TIER_C:-15s}
export LOAD_TIER_C
LOAD_RUNTIME_IMAGE=${LOAD_RUNTIME_IMAGE:-sudoit1/rahdar:dev}
out=$root/load/target
stack=$out/stack
project=rahdar-load
sample_seconds=${LOAD_SAMPLE_SECONDS:-10}

say() { printf '\n\033[1m→ %s\033[0m\n' "$*"; }

# One run at a time: the stack's name and ports are fixed.
mkdir -p "$out"
lock=$out/.running
if ! mkdir "$lock" 2>/dev/null; then
  echo "another load run is in progress ($lock exists; remove it if none is)" >&2
  exit 2
fi

COMPOSE="docker compose -p $project --env-file $stack/stack.env -f $root/deploy/compose/compose.ha.yaml -f $stack/compose.load.yaml"
sampler=""
churner=""
cleanup() {
  [ -z "$sampler" ] || kill "$sampler" 2>/dev/null || true
  # shellcheck disable=SC2086 # a list of process ids
  [ -z "${churner:-}" ] || kill $churner 2>/dev/null || true
  if [ "${LOAD_KEEP:-}" = 1 ]; then
    echo "LOAD_KEEP=1: the stack stays up on ${RAHDAR:-}; remove it with: $COMPOSE down -v --remove-orphans" >&2
    rmdir "$lock" 2>/dev/null || true
    return
  fi
  say "removing the load stack and its volumes"
  $COMPOSE down -v --remove-orphans >/dev/null 2>&1 || true
  rmdir "$lock" 2>/dev/null || true
}
trap cleanup EXIT
trap 'exit 130' INT TERM

rm -rf "$out/stack" "$out/seed" "$out/scrape" "$out/report" "$out/gatling"
mkdir -p "$stack" "$out/seed" "$out/scrape" "$out/report"

command -v docker >/dev/null || { echo "docker is required" >&2; exit 2; }
avail_mb=$(df -Pm "$out" | awk 'NR == 2 { print $4 }')
[ "$avail_mb" -ge 4096 ] || { echo "only ${avail_mb} MB free: brokers block at 90% disk use, free some space first" >&2; exit 2; }

# Compile the simulation first, so a mistake there does not cost a started stack.
(cd "$root/load" && ../mvnw -B -q test-compile) || { echo "the simulation does not compile" >&2; exit 2; }

# --- the image ---
volumes=""
if [ -n "${LOAD_JAR:-}" ]; then
  [ -f "$LOAD_JAR" ] || { echo "LOAD_JAR $LOAD_JAR does not exist (./mvnw -Pfrontend -DskipTests package)" >&2; exit 2; }
  image=$LOAD_RUNTIME_IMAGE
  volumes="    volumes:
      - $(cd "$(dirname "$LOAD_JAR")" && pwd)/$(basename "$LOAD_JAR"):/app/app.jar:ro"
elif [ -n "${LOAD_IMAGE:-}" ]; then
  image=$LOAD_IMAGE
else
  say "building the Rahdar image from the Dockerfile"
  docker build -q -t rahdar:load . >/dev/null
  image=rahdar:load
fi

# --- the stack: the shipped HA compose file plus brokers and our own port ---
db_password=$(openssl rand -hex 16)
secret_key=$(openssl rand -base64 32)
cat > "$stack/stack.env" <<ENV
DB_NAME=rahdar
DB_USER=rahdar
DB_PASSWORD=$db_password
SECRET_KEY=$secret_key
RAHDAR_IMAGE=$image
ENV
{
  cat <<YAML
# Generated by scripts/load.sh: the brokers, and Rahdar on the load test's own port.
services:
  lb:
    ports: !override
      - "127.0.0.1:$LOAD_PORT:8080"
YAML
  [ -z "${LOAD_TCP_WMEM:-}" ] || printf '    sysctls:\n      net.ipv4.tcp_wmem: "%s"\n' "$LOAD_TCP_WMEM"
  for s in rahdar-1 rahdar-2; do
    printf '  %s:\n    environment:\n      RAHDAR_SCRAPE_TIER_C_INTERVAL: %s\n' "$s" "$LOAD_TIER_C"
    [ -z "${LOAD_TIER_AB:-}" ] || printf '      RAHDAR_SCRAPE_TIER_A_INTERVAL: %s\n      RAHDAR_SCRAPE_TIER_B_INTERVAL: %s\n' "$LOAD_TIER_AB" "$LOAD_TIER_AB"
    printf '    depends_on:\n'
    i=0
    while [ "$i" -lt "$LOAD_BROKERS" ]; do
      printf '      broker-%d:\n        condition: service_healthy\n' "$i"
      i=$((i + 1))
    done
    [ -z "${LOAD_TCP_WMEM:-}" ] || printf '    sysctls:\n      net.ipv4.tcp_wmem: "%s"\n' "$LOAD_TCP_WMEM"
    [ -z "$volumes" ] || printf '%s\n' "$volumes"
  done
  i=0
  while [ "$i" -lt "$LOAD_BROKERS" ]; do
    cat <<YAML
  broker-$i:
    image: apache/artemis:2.57.0
    environment:
      ARTEMIS_USER: artemis
      ARTEMIS_PASSWORD: artemis
      ANONYMOUS_LOGIN: "false"
      JAVA_ARGS_APPEND: "-Xms64m -Xmx${LOAD_BROKER_HEAP}m"
    ports:
      - "127.0.0.1::8161"
    healthcheck:
      # The image has no curl, so bash speaks HTTP itself (as in the dev stack).
      test: ["CMD", "bash", "-c", "exec 3<>/dev/tcp/localhost/8161 && printf 'GET /console/jolokia/search/org.apache.activemq.artemis:broker=* HTTP/1.0\\\\r\\\\nAuthorization: Basic %s\\\\r\\\\n\\\\r\\\\n' \"\$\$(printf artemis:artemis | base64)\" >&3 && grep -q '\"value\":\\\\[\"' <&3"]
      interval: 5s
      timeout: 5s
      retries: 30
YAML
    i=$((i + 1))
  done
} > "$stack/compose.load.yaml"

say "starting the stack: 2 Rahdar replicas, HAProxy, Postgres, $LOAD_BROKERS brokers"
$COMPOSE config -q
$COMPOSE up -d --wait --wait-timeout 600

export RAHDAR=http://127.0.0.1:$LOAD_PORT COMPOSE SEED_DIR=$out/seed
export LOAD_BROKERS LOAD_CLUSTERS LOAD_NODES_PER_CLUSTER LOAD_QUEUES LOAD_MESSAGES LOAD_AUDIT_ROWS LOAD_ACCOUNTS

# The one-time password the first boot printed; the admin chooses its own and enrols a second factor.
logs=$($COMPOSE logs --no-log-prefix rahdar-1 rahdar-2 2>/dev/null || true)
ADMIN_PASSWORD=$(awk '/^ *password: / { print $2; exit }' <<<"$logs")
[ -n "$ADMIN_PASSWORD" ] || { echo "no one-time admin password in the Rahdar logs" >&2; exit 1; }
NEW_ADMIN_PASSWORD=$(openssl rand -hex 16)
export ADMIN_PASSWORD NEW_ADMIN_PASSWORD

say "seeding"
"$root/scripts/load-seed.sh"

# --- metrics ---
scrape() { # label
  local r
  for r in rahdar-1 rahdar-2; do
    $COMPOSE exec -T "$r" curl -sf http://localhost:8080/actuator/prometheus > "$out/scrape/$1-$r.prom" 2>/dev/null || true
  done
}
sample_loop() {
  local n=0
  while :; do
    n=$((n + 1))
    scrape "$(printf 'sample-%04d' "$n")"
    # shellcheck disable=SC2046 # one argument per container id
    docker stats --no-stream --format '{{.Name}} cpu={{.CPUPerc}} mem={{.MemUsage}}' \
      $($COMPOSE ps -q) > "$out/scrape/$(printf 'stats-%04d' "$n").txt" 2>/dev/null || true
    sleep "$sample_seconds"
  done
}

# Messages keep arriving during the run (LOAD_CHURN producers in parallel), so the streams carry queue and event
# frames and a stalled subscriber's socket really fills.
churn_loop() {
  local i q
  while :; do
    i=0
    while [ "$i" -lt "$LOAD_BROKERS" ]; do
      # Ten queues in turn, so that many queues change at once and the streams carry many change signals.
      q=0
      while [ "$q" -lt 10 ] && [ "$q" -lt "$LOAD_QUEUES" ]; do
        $COMPOSE exec -T -e 'JAVA_ARGS_APPEND=-Xms16m -Xmx64m -XX:+UseSerialGC' "broker-$i" /var/lib/artemis-instance/bin/artemis producer \
          --url tcp://localhost:61616 --user artemis --password artemis --destination "queue://load.q.$q" \
          --message-count 100 --message-size 512 >/dev/null 2>&1 || true
        q=$((q + 1))
      done
      i=$((i + 1))
    done
  done
}

say "running the simulation (profile $profile, ${LOAD_DURATION}s)"
scrape before
sample_loop &
sampler=$!

if [ "${LOAD_CHURN:-0}" = 1 ]; then
  churn_loop &
  churner=$!
fi

pages=$(((LOAD_QUEUES + 99) / 100))
rc=0
capped() {
  if command -v systemd-run >/dev/null 2>&1 && systemd-run --user --scope -q true 2>/dev/null; then
    systemd-run --user --scope -q -p "MemoryMax=${LOAD_GATLING_MEMORY:-2G}" -- "$@"
  else
    "$@"
  fi
}
(
  cd "$root/load"
  capped ../mvnw -B -q gatling:test \
    -Dload.profile="$profile" -Dload.url="$RAHDAR" -Dload.seed="$out/seed" -Dload.report="$out/report" \
    -Dload.duration="$LOAD_DURATION" -Dload.ramp="$LOAD_RAMP" -Dload.users="$LOAD_UI_USERS" \
    -Dload.sse.fast="$LOAD_SSE_FAST" -Dload.sse.stalled="$LOAD_SSE_STALLED" -Dload.exports="$LOAD_EXPORTS" \
    -Dload.sql="$LOAD_SQL" -Dload.queue.pages="$pages"
) || rc=$?

kill "$sampler" $churner 2>/dev/null || true
wait "$sampler" $churner 2>/dev/null || true
sampler=""
churner=""
scrape after
# Query plans and the event writer's throughput, from the database itself.
$COMPOSE exec -T postgres psql -q -U rahdar -d rahdar < "$root/load/explain.sql" > "$out/report/explain.txt" 2>&1 || true

say "report"
version=$(git describe --tags --always 2>/dev/null || echo unknown)
summary_rc=0
python3 -I "$root/scripts/load-summary.py" --profile "$profile" --version "$version" --gatling "$out/gatling" \
  --scrape "$out/scrape" --counts "$out/report/simulation-counts.json" --sizing "$root/docs/sizing.md" \
  --out "$out/report" || summary_rc=$?
[ "$rc" = 0 ] || echo "the simulation failed an assertion or could not run (exit $rc)" >&2
[ "$summary_rc" = 0 ] || echo "REGRESSION: a figure is below its published target" >&2
[ "$rc" = 0 ] && [ "$summary_rc" = 0 ]
